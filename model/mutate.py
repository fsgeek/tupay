def replace_def(src, name, new):
    # derives: P1, P4, P7, P8 -- replace the definition block of `name` (with its comments)
    lines = src.split("\n")
    start = next(i for i, l in enumerate(lines) if re.match(rf"^{name}(\(| ==)", l))
    while start > 0 and lines[start - 1].startswith("\\*"):
        start -= 1
    end = start
    while end < len(lines) and lines[end].strip() != "":
        end += 1
    return "\n".join(lines[:start] + new.rstrip("\n").split("\n") + lines[end:])


def build(pair, derives, desc, edits, src):
    # derives: P1, P2, P3, P4, P5, P6, P7, P8, P9, P10, P11, P12
    for kind, a, b in edits:
        if kind == "def":
            src = replace_def(src, a, b)
        else:
            n = src.count(a)
            if n != 1:
                raise SystemExit(f"{pair}: anchor occurs {n} times: {a!r}")
            src = src.replace(a, b)
    head, rest = src.split("\n", 1)
    return (head + f"\n\\* mutation: {pair} {desc}\n\\* derives: {pair}, {derives}\n" + rest)


def main(only=()):
    src = (HERE / "Lease.tla").read_text()
    for pair, derives, _, desc, edits in MUTATIONS:
        if only and pair not in only:
            continue
        d = HERE / "mutations" / pair
        d.mkdir(parents=True, exist_ok=True)
        (d / "Lease.tla").write_text(build(pair, derives, desc, edits, src))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
