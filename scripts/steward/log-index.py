#!/usr/bin/env python3
"""Generate docs/steward/log-index.md: a bounded index of docs/seed-log.md that declares what it omits.
The log is append-only evidence; this index is how a steward finds things in it without reading it whole,
and without the silent truncation of "read the tail" (log 2026-10-22, "the replay models reached first-version
unnoticed"; the MEMORY.md load limit was the same failure). Regenerate after appending to the log.
derives: AGENTS.md rule 1; docs/steward-practice.md "Records"."""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LOG, OUT = ROOT / "docs/seed-log.md", ROOT / "docs/steward/log-index.md"
RECENT = 12
KINDS = [  # (label, heading pattern); an entry is listed under the first kind it matches
    ("Errors, lapses and corrections", r"error|lapse|correction|withdrawn|wrong|exhausted the machine|leak"),
    ("Results, registrations and handoffs", r"scored|result|registered|registration|accepts|hands off|handoff|closed|reached M"),
    ("Practice and decisions", r"practice|decision|rule|freeze|frozen|reopened|do both|parallel"),
]

entries = [(i + 1, l[3:].strip()) for i, l in enumerate(LOG.read_text().splitlines()) if l.startswith("## ")]
listed, out = set(), []
out += ["# Index of the seed log (generated)", "",
        f"Generated by `scripts/steward/log-index.py` from `docs/seed-log.md` ({len(entries)} entries). "
        "The log outranks this file. Line numbers are the heading's line in the log. "
        "Entries are listed by heading only; read the entry before relying on it.", ""]
out += [f"## The {RECENT} most recent entries", ""]
for n, h in entries[-RECENT:]:
    out.append(f"- L{n}: {h}"); listed.add(n)
for label, pat in KINDS:
    rows = [(n, h) for n, h in entries if n not in listed and re.search(pat, h, re.I)]
    out += ["", f"## {label} (older)", ""] + [f"- L{n}: {h}" for n, h in rows]
    listed.update(n for n, _ in rows)
omitted = len(entries) - len(listed)
out += ["", "## Omitted", "",
        f"{omitted} of {len(entries)} entries are not listed here. They are in the log; search it "
        "(`grep -n -i '<topic>' docs/seed-log.md`) for anything your task touches before deciding it, "
        "and search khipumaq for anything said outside the log."]
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(out) + "\n")
print(f"{OUT.relative_to(ROOT)}: {len(listed)} listed, {omitted} omitted", file=sys.stderr)
