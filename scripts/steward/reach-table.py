#!/usr/bin/env python3
"""Needed reach per shared schedule, read from the schedule text (X3 prereg, support audit; Fable finding 5).
derives: docs/steward-practice.md "Support audit before scoring a bounded check"; testbed/schedule-format.md v2.2 to v5
usage: uv run --with pyyaml python3 scripts/steward/reach-table.py testbed/schedules/*.yaml > experiments/X3/reach.md
Each column is a floor the model's bounds must admit for that schedule; it is computed, not judged, so it cannot be
fitted to an arm after the fact. "epochs" counts reconfigurations the schedule waits on or that C3.4(b) owes;
"terms" is 2 where the grantor is crashed, partitioned, cut, removed or replaced, else 1; "ticks" is the largest
clock step in ticks (lifetime x step)."""
import sys, yaml
from fractions import Fraction
from pathlib import Path
print("# X3 needed reach per shared schedule (generated by `scripts/steward/reach-table.py`; do not edit)\n")
print("| Schedule | lease/config | clients | grants | reconfig sent | epochs | crashes | amnesic | clock steps | max ticks | terms |")
print("|---|---|---|---|---|---|---|---|---|---|---|")
for p in sorted(sys.argv[1:], key=lambda x: (Path(x).stem[0], int(''.join(c for c in Path(x).stem if c.isdigit()) or 0))):
    d = yaml.safe_load(Path(p).read_text()); pr = d['processes']; life = d.get('lifetime', 1)
    lease, config = pr['lease'], pr.get('config', pr['lease'])
    steps = d['steps']; acts = [s['do'] for s in steps]; ats = [s['at'] for s in steps]
    req = sum(1 for a in acts if 'request' in a)
    rec = [a for a in acts if 'reconfigure' in a]
    waited = {a.get('request_id') for a in ats if isinstance(a, dict) and a.get('event') in ('ConfigCommitted', 'ReconfigAck')}
    # at least one commit wherever a non-empty request is sent: otherwise C3.1 and C3.8 hold vacuously (first version
    # counted only waited-on requests, so P31, P32, P61, P62, P63 read 0; caught reading the table, before commit)
    epochs = max(len([r for r in rec if r['id'] in waited]), 1 if any(r['reconfigure'] for r in rec) else 0)
    crashes = sum(1 for a in acts if 'crash' in a); amn = sum(1 for a in acts if a.get('amnesia'))
    clocks = [a for a in acts if 'clock' in a]
    ticks = max([abs(Fraction(str(a['step'])) * life) for a in clocks], default=0)
    hit = any(a.get('crash') == 'grantor' or 'partition' in a or 'cut' in a or 'drop' in a or
              ('reconfigure' in a and not set(config) <= set(a['reconfigure'])) for a in acts)
    print(f"| {Path(p).stem} | {len(lease)}/{len(config)} | {len(pr['clients'])} | {req} | {len(rec)} | {epochs} | "
          f"{crashes} | {amn} | {len(clocks)} | {ticks} | {2 if hit else 1} |")
