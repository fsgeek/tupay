#!/usr/bin/env python3
"""X3 support audit, compile half: one schedule, one model side -> a TLC probe that asks whether the side's checked
space contains a state meeting every floor of the schedule's registered reach row.

derives: experiments/X3-prereg.md Departure 3 ("support audit is registered"; probe method; "no support";
         "vacuous by design") and measure 1(a); experiments/X3/reach.md, experiments/X3/holdout/reach.md (the floors,
         generated by scripts/steward/reach-table.py); scripts/steward/x3-runs.sh (how the sides were run)
usage: probe.py <A|R> <schedule-id> <outdir> <mutant: 0|1>
Writes into <outdir> only: src/ (copies of the side's compile.py, Lease.tla, the schedule), tlc/ (the side's own
compiled MC module and cfgs, written by the side's own compiler at the side's own default bounds, plus Probe.tla and
Probe.cfg), floors.txt (column, floor, TLA+ expression, how it is counted) and plan.json (read by audit.sh).
The clones are read, never written: their files are copied into <outdir>/src and the compiler is imported from there
with bytecode writing off. Column-to-expression mapping and its judgement calls: MAPPING.md beside this file.
mutant 1 (anti-theater): the epochs floor is set to the schedule's number of reconfigure steps + 1, which no run can
reach (each request commits at most one epoch), so the probe must come back NO-SUPPORT.
"""
import hashlib
import importlib.util
import json
import os
import re
import shutil
import sys
from pathlib import Path

sys.dont_write_bytecode = True
import yaml  # noqa: E402

TUPAY = Path(__file__).resolve().parents[3]
HOME = Path.home()
CLONE = {'A': Path(os.environ.get('AUDIT_CLONE_A', HOME / 'projects/tupay-x3-score/armA-model')),
         'R': Path(os.environ.get('AUDIT_CLONE_R', HOME / 'projects/tupay-x3-score/armR-model'))}
SUB = {'A': 'model', 'R': 'model-regen'}
HOLDOUT = TUPAY / 'experiments/X3/holdout'
COLS = ['lease', 'config', 'clients', 'grants', 'reconfig', 'epochs', 'crashes', 'amnesic', 'clocksteps',
        'maxticks', 'terms']

# derives: experiments/X3-prereg.md Departure 3 -- per side, per column: (kind, TLA+ expression with {k}).
# kind: "structural" (a compiled constant, checked here and also conjoined), "state" (a model variable),
#       "step" (counted by the schedule position: steps 1..pc-1 have been taken), "vacuous" (not modelled).
# Citations and judgement calls: MAPPING.md.
EXPR = {
    'A': {
        'lease': ('structural', 'Cardinality(Nodes) >= {k}'),
        'config': ('structural', 'Cardinality(Init0) >= {k}'),
        'clients': ('structural', 'Cardinality(Clients) >= {k}'),
        'grants': ('state', 'Len(grants) >= {k}'),
        'reconfig': ('step', 'AuditStepsDone("reconfig") >= {k}'),
        'epochs': ('state', '\\E ai \\in 1..Len(commits) : commits[ai].rec.ep >= {k}'),
        'crashes': ('step', 'AuditStepsDone("crash") >= {k}'),
        'amnesic': ('state', 'AuditSum(inc, Nodes) >= {k}'),
        'clocksteps': ('step', 'AuditStepsDone("clock") >= {k}'),
        'maxticks': ('step', '\\E ai \\in 1..(pc - 1) : Steps[ai].kind = "clock" /\\ (Steps[ai].s >= {k} \\/ -Steps[ai].s >= {k})'),
        'terms': ('state', '(\\E ai \\in 1..Len(grants) : grants[ai].term >= {k}) \\/ (\\E an \\in Nodes : leader[an] /\\ term[an] >= {k})'),
    },
    'R': {
        'lease': ('structural', 'Len(LeaseSeq) >= {k}'),
        'config': ('structural', 'Cardinality(InitCfg) >= {k}'),
        'clients': ('structural', 'Cardinality(Clients) >= {k}'),
        'grants': ('state', 'Cardinality(gr) >= {k}'),
        'reconfig': ('state', 'Cardinality(rqs) >= {k}'),
        'epochs': ('state', 'GCur >= {k}'),
        'crashes': ('step', 'AuditStepsDone("crash") >= {k}'),
        'amnesic': ('state', 'AuditSum(inc, Lease) >= {k}'),
        # no clock in the model (Lease.tla header, DoAct "clock"): the step is taken and recorded, no state changes
        'clocksteps': ('vacuous', 'AuditStepsDone("clock") >= {k}'),
        'maxticks': ('vacuous', '\\E ai \\in 1..(pc - 1) : Steps[ai].do.a = "clock" /\\ (Steps[ai].do.ticks >= {k} \\/ -Steps[ai].do.ticks >= {k})'),
        'terms': ('state', '(\\E ag \\in gr : ag.term >= {k}) \\/ (\\E an \\in Lease : role[an] = "L" /\\ term[an] >= {k})'),
    },
}
# derives: experiments/X3-prereg.md Departure 3 -- the step kind field per side (A: Steps[ai].kind; R: Steps[ai].do.a)
STEPKIND = {'A': 'Steps[ai].kind', 'R': 'Steps[ai].do.a'}


def die(msg):
    print(f'probe.py: {msg}', file=sys.stderr)
    sys.exit(2)


def reach_rows():
    """derives: experiments/X3/reach.md, experiments/X3/holdout/reach.md -- the registered floors, as committed"""
    rows = {}
    for f in (TUPAY / 'experiments/X3/reach.md', HOLDOUT / 'reach.md'):
        for ln in f.read_text().splitlines():
            m = re.match(r'^\| ([\w-]+) \| (\d+)/(\d+) \|(.*)\|\s*$', ln)
            if not m:
                continue
            rest = [c.strip() for c in m.group(4).split('|')]
            vals = [int(m.group(2)), int(m.group(3))] + [int(x) for x in rest]
            if len(vals) != len(COLS):
                die(f'reach row {m.group(1)} has {len(vals)} columns')
            rows[m.group(1)] = dict(zip(COLS, vals))
    return rows


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def main(argv):
    if len(argv) != 5 or argv[1] not in ('A', 'R') or argv[4] not in ('0', '1'):
        die(__doc__)
    side, sid, out, mutant = argv[1], argv[2], Path(argv[3]), argv[4] == '1'
    clone = CLONE[side]
    model = clone / SUB[side]
    rows = reach_rows()
    if sid not in rows:
        die(f'no registered reach row for {sid}')
    floors = dict(rows[sid])
    notes = []
    # the schedule: hold-outs from the committed, hash-checked copies; the rest from the side's clone, compared with main
    if re.fullmatch(r'H1[1-4]', sid):
        sched = HOLDOUT / f'{sid}.yaml'
        want = {l.split()[1].split('/')[-1]: l.split()[0] for l in (HOLDOUT / 'SHA256SUMS').read_text().splitlines()}
        if want.get(f'{sid}.yaml') != sha(sched):
            die(f'hold-out {sid} hash mismatch')
        notes.append(f'schedule: experiments/X3/holdout/{sid}.yaml (hash matches SHA256SUMS)')
    else:
        sched = clone / 'testbed/schedules' / f'{sid}.yaml'
        if not sched.exists():
            die(f'no schedule {sched}')
        mainc = TUPAY / 'testbed/schedules' / f'{sid}.yaml'
        same = mainc.exists() and sha(mainc) == sha(sched)
        notes.append(f'schedule: clone testbed/schedules/{sid}.yaml ({"same as" if same else "DIFFERENT from"} main)')
    src, tlc = out / 'src', out / 'tlc'
    src.mkdir(parents=True)
    tlc.mkdir(parents=True)
    for f in ('compile.py', 'Lease.tla'):
        shutil.copy(model / f, src / f)
    shutil.copy(sched, src / f'{sid}.yaml')
    doc = yaml.safe_load((src / f'{sid}.yaml').read_text())
    nreconf = sum(1 for s in doc['steps'] if 'reconfigure' in (s.get('do') or {}))
    if mutant:
        floors['epochs'] = nreconf + 1
        notes.append(f'MUTANT: epochs floor raised to {nreconf + 1} (reconfigure steps + 1; unreachable by design)')

    spec = importlib.util.spec_from_file_location('side_compile', src / 'compile.py')
    C = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(C)
    # derives: scripts/steward/x3-runs.sh (run.sh <name>, no flags) -- the side's own compiler at its own defaults
    if side == 'A':
        # model/run.py check(): compiler.compile_schedule(path, dirp, Lease.tla) -> MC.tla, MC.cfg
        meta = C.compile_schedule(src / f'{sid}.yaml', tlc, src / 'Lease.tla')
        base_cfg = (tlc / 'MC.cfg').read_text()
        cfg = ''.join(l + '\n' for l in base_cfg.splitlines()
                      if not l.startswith('INVARIANT') and not l.startswith('PROPERTY'))
        bounds = f"MaxTerm {meta['max_term']}, MaxDups {meta['max_dups']}"
        nodes, cfgm, clients = (len(meta['processes']['lease']), len(meta['processes']['config']),
                                len(meta['processes']['clients']))
        author_cfg, tlc_flags = 'MC.cfg', '-deadlock -cleanup -checkpoint 5'
        cap = meta['max_term']
    else:
        # model-regen/run.py run_one(name): C.compile_schedule(sched, None, None); C.write_outputs(..., 'Lease')
        const, meta = C.compile_schedule(doc, None, None)
        C.write_outputs(const, meta, str(tlc), 'Lease')
        shutil.copy(src / 'Lease.tla', tlc / 'Lease.tla')
        base_cfg = (tlc / 'safety.cfg').read_text()
        # the author's safety run, without its invariants and action properties; deadlock checking off (a terminal
        # state is not a reach question, and TLC would stop at the first one)
        cfg = base_cfg.split('INVARIANTS')[0].replace('CHECK_DEADLOCK TRUE', 'CHECK_DEADLOCK FALSE')
        bounds = (f"MaxTerm {meta['max_term']} (TermCap MaxTerm + {len(meta['lease'])} after the last fault), "
                  f"Spur0 {meta['spur']}")
        nodes, cfgm, clients = len(meta['lease']), len(meta['config']), len(meta['clients'])
        author_cfg, tlc_flags = 'safety.cfg', '-nowarning'
        cap = meta['max_term'] + len(meta['lease'])
    (tlc / 'Probe.cfg').write_text(f'\\* derives: experiments/X3-prereg.md Departure 3 (support audit); '
                                   f'the author\'s {author_cfg} with NoFloor as the only invariant\n'
                                   + cfg + 'INVARIANT NoFloor\n')

    # structural floors, from the compiled constants
    structural = {'lease': nodes, 'config': cfgm, 'clients': clients}
    smiss = [f'{c} needs {floors[c]}, compiled {structural[c]}' for c in structural if structural[c] < floors[c]]

    defs, lines, used, vac = [], [], [], []
    for c in COLS:
        kind, e = EXPR[side][c]
        k = floors[c]
        expr = e.format(k=k)
        lines.append(f'{c}\tfloor {k}\t{kind}\t{expr if k > 0 else "(floor 0: not conjoined)"}')
        if k <= 0:
            continue
        defs.append(f'AuditF_{c} == {expr}')
        used.append(c)
        if kind == 'vacuous':
            vac.append(c)
    mod = ['---- MODULE Probe ----',
           f'\\* derives: experiments/X3-prereg.md Departure 3 (support audit), experiments/X3/reach.md row {sid}'
           + (' (MUTANT: epochs floor raised)' if mutant else ''),
           'EXTENDS MC, Integers, FiniteSets, Sequences, TLC',
           '\\* derives: experiments/X3-prereg.md Departure 3 -- sum of a function over a finite set (incarnations)',
           'RECURSIVE AuditSum(_, _)',
           'AuditSum(auditF, auditS) == IF auditS = {} THEN 0 ELSE LET auditX == CHOOSE auditY \\in auditS : TRUE '
           'IN auditF[auditX] + AuditSum(auditF, auditS \\ {auditX})',
           '\\* derives: experiments/X3-prereg.md Departure 3 -- schedule steps of kind k already taken (1..pc-1)',
           f'AuditStepsDone(auditK) == Cardinality({{ai \\in 1..(pc - 1) : {STEPKIND[side]} = auditK}})',
           '\\* derives: experiments/X3/reach.md -- one conjunct per nonzero floor of the row (MAPPING.md)']
    mod += defs
    mod.append('Floor == ' + (' /\\ '.join(f'AuditF_{c}' for c in used) if used else 'TRUE'))
    mod.append('NoFloor == ~Floor')
    for c in used:   # for SPLIT=1 diagnosis: each floor alone
        mod.append(f'AuditNo_{c} == ~AuditF_{c}')
    mod.append('====')
    (tlc / 'Probe.tla').write_text('\n'.join(mod) + '\n')
    (out / 'floors.txt').write_text(
        f'side {side} schedule {sid} mutant {int(mutant)}\nbounds (the side\'s own defaults): {bounds}\n'
        + '\n'.join(notes) + '\n' + '\n'.join(lines) + '\n')
    plan = {'side': side, 'schedule': sid, 'mutant': mutant, 'floors': floors, 'used': used, 'vacuous': vac,
            'structural_miss': smiss, 'bounds': bounds, 'term_cap': cap, 'tlc_flags': tlc_flags,
            'notes': notes}
    json.dump(plan, open(out / 'plan.json', 'w'), indent=1)
    print(json.dumps({'used': used, 'vacuous': vac, 'structural_miss': smiss, 'flags': tlc_flags}))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
